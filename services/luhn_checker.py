def check_luhn(number: str) -> bool:
    """Проверяет номер по алгоритму Луна."""

    digits = [int(digit) for digit in number]

    total = 0
    parity = len(digits) % 2

    for i, digit in enumerate(digits):
        if i % 2 == parity:
            digit *= 2

            if digit > 9:
                digit -= 9

        total += digit

    return total % 10 == 0

# Принцип работы алгоритма:
# Нумерация идет справа налево (от последней цифры к первой):
# 1. Оставляем нечётные позиции справа без изменений (1-я, 3-я, 5-я и т.д. от конца).
# 2. Удваиваем чётные позиции справа (2-я, 4-я, 6-я и т.д.).
# 3. Если после умножения на 2 получилось число больше 9, то из него вычитают 9 (или просто складывают две цифры этого числа).
# 4. Суммируют все полученные цифры (и измененные, и оставшиеся без изменений).
# 5. Проверяют остаток: если общая сумма делится на 10 без остатка (сумма % 10 == 0), то номер считается верным.